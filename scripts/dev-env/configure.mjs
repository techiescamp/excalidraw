#!/usr/bin/env node
// The two file rewrites unproduction.sh performs on the development droplet,
// kept here rather than inline in the shell script so they can be tested
// without a droplet. configure.test.mjs is that test.
//
//   node configure.mjs env <path-to-env-file>
//   node configure.mjs nginx <source-site> <target-site>
//
// Values arrive through the environment, never as arguments, so a key cannot
// be read off a process list.
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

/**
 * Replaces the given keys in a systemd EnvironmentFile, leaving every other
 * line — comments included — exactly as it was. A key that appears twice is
 * reduced to one line, because a repeat would shadow the rewritten value.
 */
export const rewriteEnv = (text, changes) => {
  const out = [];
  const seen = new Set();
  for (const line of text.split("\n")) {
    const key = line.includes("=") ? line.split("=", 1)[0].trim() : "";
    if (!(key in changes)) {
      out.push(line);
      continue;
    }
    if (seen.has(key)) {
      continue;
    }
    seen.add(key);
    out.push(`${key}=${changes[key]}`);
  }
  // A trailing empty line from the split, so new keys go before it.
  while (out.length && out[out.length - 1] === "") {
    out.pop();
  }
  for (const [key, value] of Object.entries(changes)) {
    if (!seen.has(key)) {
      out.push(`${key}=${value}`);
    }
  }
  return `${out.join("\n")}\n`;
};

const topLevelBlocks = (text) => {
  const blocks = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === "{") {
      depth += 1;
    } else if (text[i] === "}") {
      depth -= 1;
      if (depth === 0) {
        blocks.push(text.slice(start, i + 1));
        start = i + 1;
      }
    }
  }
  return blocks;
};

// Lines that only make sense for a site with a certificate and a name.
const TLS_OR_NAME =
  /^\s*(listen\b|server_name\b|http2\b|ssl_\w+\b|return\s+301\s+https|if\s*\(\$host|include\s+\S*options-ssl-nginx)/;

/**
 * Turns the production nginx site into one that answers on port 80 for any
 * name, which is what an IP address needs.
 *
 * certbot moves the real configuration into the 443 block and leaves an 80
 * block that redirects to HTTPS. On an IP that redirect leads to a certificate
 * issued for another name, so the redirect block is dropped and the real block
 * is given a plain listener. Everything else in it — the proxy, the caches, the
 * security headers — is kept verbatim: this is a development box, not a
 * different application.
 */
export const devNginxSite = (text, sourcePath = "the production site") => {
  const blocks = topLevelBlocks(text);
  const head = blocks.filter((b) => !b.trimStart().startsWith("server"));
  const servers = blocks.filter((b) => b.trimStart().startsWith("server"));

  // The block that proxies to the API is the real one.
  const real = servers.find((b) => b.includes("127.0.0.1:4000"));
  if (!real) {
    throw new Error("no server block proxies to the API; refusing to guess");
  }

  const kept = real.split("\n").filter((line) => !TLS_OR_NAME.test(line));
  const opened = kept.findIndex((line) => line.includes("{"));
  if (opened === -1) {
    throw new Error("the server block has no opening brace");
  }
  kept.splice(
    opened + 1,
    0,
    "    # Development box: HTTP on the droplet's address. No TLS, no redirect.",
    "    listen 80;",
    "    listen [::]:80;",
    "    server_name _;",
  );

  const preamble = head.join("").trim();
  const site = [
    `# Generated by scripts/dev-env/configure.mjs from ${sourcePath}`,
    "# The original is unchanged; this file is what is enabled.",
    ...(preamble ? [preamble, ""] : []),
    kept.join("\n").trim(),
    "",
  ].join("\n");
  // Removing a block leaves the blank lines that surrounded it behind.
  return site.replace(/\n{3,}/g, "\n\n");
};

// The keys unproduction.sh replaces, and where their values come from.
const envChanges = (env) => ({
  APP_ORIGIN: env.NEW_APP_ORIGIN ?? "",
  COOKIE_SECURE: "false",
  JWT_SECRET: env.NEW_JWT_SECRET ?? "",
  // Empty when no dev bucket was given: the server then falls back to its
  // local-disk driver, which cannot reach production storage at all.
  AWS_ACCESS_KEY_ID: env.DEV_S3_KEY_ID ?? "",
  AWS_SECRET_ACCESS_KEY: env.DEV_S3_SECRET ?? "",
  S3_BUCKET: env.DEV_S3_BUCKET ?? "",
  S3_ENDPOINT: env.DEV_S3_ENDPOINT ?? "",
  AWS_REGION: env.DEV_S3_REGION ?? "",
  // Alerts are production's business.
  DISCORD_WEBHOOK: "",
});

const main = (argv) => {
  const [action, ...rest] = argv;
  if (action === "env") {
    const [path] = rest;
    if (!path) {
      throw new Error("usage: configure.mjs env <path>");
    }
    const changes = envChanges(process.env);
    if (!changes.APP_ORIGIN || !changes.JWT_SECRET) {
      throw new Error("NEW_APP_ORIGIN and NEW_JWT_SECRET must both be set");
    }
    writeFileSync(path, rewriteEnv(readFileSync(path, "utf8"), changes));
    return;
  }
  if (action === "nginx") {
    const [source, target] = rest;
    if (!source || !target) {
      throw new Error("usage: configure.mjs nginx <source> <target>");
    }
    writeFileSync(target, devNginxSite(readFileSync(source, "utf8"), source));
    return;
  }
  throw new Error("usage: configure.mjs env <path> | nginx <source> <target>");
};

// Only when run as a program, so the test can import the two functions.
const invokedDirectly =
  process.argv[1] &&
  import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href;
if (invokedDirectly) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(`configure: ${error.message}`);
    process.exit(1);
  }
}
